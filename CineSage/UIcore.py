# -------------------- Helper Functions --------------------
def format_movie_text(movie):
    """Convert movie data into a readable TXT report."""

    genres = movie.get("genre") or []
    cast = movie.get("cast") or []

    if isinstance(genres, str):
        genres = [genres]

    if isinstance(cast, str):
        cast = [cast]

    lines = [
        f"MOVIE INFORMATION: {movie.get('title') or 'Not available'}",
        "=" * 45,
        "",
        f"Title: {movie.get('title') or 'Not available'}",
        f"Release Year: {movie.get('release_year') if movie.get('release_year') is not None else 'Not available'}",
        f"Genre: {', '.join(map(str, genres)) if genres else 'Not available'}",
        f"Director: {movie.get('director') or 'Not available'}",
        f"Rating: {movie.get('rating') if movie.get('rating') is not None else 'Not available'}",
        "",
        "Cast:",
    ]

    if cast:
        lines.extend([f"- {person}" for person in cast])
    else:
        lines.append("- Not available")

    lines.extend([
        "",
        "SUMMARY",
        "-" * 20,
        movie.get("summary") or "Not available",
        "",
        "Generated by CineSage",
        "© 2026 Bishnuprasad",
    ])

    return "\n".join(lines)


def display_movie(movie):
    """Display readable movie details and download options."""

    if hasattr(movie, "model_dump"):
        movie = movie.model_dump()

    title = movie.get("title") or "Movie not identified"
    year = movie.get("release_year")
    genres = movie.get("genre") or []
    director = movie.get("director")
    cast = movie.get("cast") or []
    rating = movie.get("rating")
    summary = movie.get("summary") or "Not available"

    if isinstance(genres, str):
        genres = [genres]

    if isinstance(cast, str):
        cast = [cast]

    # Readable chatbot-style response
    st.markdown(f"## 🎬 {title}")

    st.markdown("### Movie details")

    st.markdown(f"- **Title:** {title}")
    st.markdown(
        f"- **Release year:** "
        f"{year if year is not None else 'Not available'}"
    )
    st.markdown(
        f"- **Genre:** "
        f"{', '.join(map(str, genres)) if genres else 'Not available'}"
    )
    st.markdown(f"- **Director:** {director or 'Not available'}")
    st.markdown(
        f"- **Rating:** "
        f"{rating if rating is not None else 'Not available'}"
    )

    st.markdown("### 🎭 Cast")

    if cast:
        for person in cast:
            st.markdown(f"- {person}")
    else:
        st.markdown("- Not available")

    st.markdown("### 📖 Summary")
    st.markdown(
        f'<div class="movie-summary">{summary}</div>',
        unsafe_allow_html=True,
    )

    # Prepare downloads
    json_data = json.dumps(
        movie,
        indent=4,
        ensure_ascii=False,
    )

    text_data = format_movie_text(movie)

    safe_title = "".join(
        char for char in title
        if char.isalnum() or char in (" ", "-", "_")
    ).strip()

    safe_title = safe_title.replace(" ", "_") or "movie_details"

    st.markdown("---")
    st.markdown("### 📥 Download movie information")

    col1, col2 = st.columns(2)

    with col1:
        st.download_button(
            label="⬇️ Download JSON",
            data=json_data,
            file_name=f"{safe_title}.json",
            mime="application/json",
            use_container_width=True,
        )

    with col2:
        st.download_button(
            label="⬇️ Download TXT",
            data=text_data,
            file_name=f"{safe_title}.txt",
            mime="text/plain",
            use_container_width=True,
        )

    # Raw JSON is available if the user needs it.
    with st.expander("View structured JSON"):
        st.json(movie)


# -------------------- Main UI --------------------
st.title("🎬 Movie Information Extractor")

st.write(
    "Describe a movie or paste a paragraph. "
    "CineSage will extract its details and present them "
    "in an easy-to-read format."
)

paragraph = st.text_area(
    "Enter Movie Paragraph",
    height=200,
    placeholder=(
        "Example: Spider-Man is a superhero film directed "
        "by Sam Raimi, starring Tobey Maguire..."
    ),
)

# Keep results visible across Streamlit reruns.
if "movie_result" not in st.session_state:
    st.session_state.movie_result = None

if st.button("Extract Data", type="primary", use_container_width=True):
    if not paragraph.strip():
        st.warning("Please enter a paragraph first.")

    else:
        with st.spinner("Analyzing movie..."):
            try:
                movie = extract_movie(paragraph)

                if hasattr(movie, "model_dump"):
                    movie_data = movie.model_dump()
                elif isinstance(movie, dict):
                    movie_data = movie
                else:
                    raise TypeError(
                        "extract_movie() must return a Movie "
                        "object or dictionary."
                    )

                st.session_state.movie_result = movie_data

            except Exception as error:
                st.session_state.movie_result = None

                st.error(
                    "Failed to extract movie information. "
                    "Please check your Groq API key and try again."
                )

                with st.expander("Technical details"):
                    st.exception(error)

# Display the saved result.
if st.session_state.movie_result:
    st.divider()
    display_movie(st.session_state.movie_result)
    st.success("Extraction completed successfully!")


